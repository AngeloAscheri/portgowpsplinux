/* On-screen notices (Linux, phase 10 of docs/linux.md): one at a time, top centre, for about 6 s with a fade in and
 * out, over the game without pausing it. Each is drawn once on the CPU, for the window's height (a tenth of it),
 * with the game picker's Cinzel (stb_truetype) and its icon (a PNG, read by SDL); rt_gpu.c uploads and draws it. */
