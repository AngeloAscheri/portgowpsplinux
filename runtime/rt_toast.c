#define QUEUE 8
#define FADE_IN_MS 250u
#define HOLD_MS 5500u
#define FADE_OUT_MS 500u
#define OPACITY 0.94f

typedef struct { char head[64], right[48], title[192], text[400]; uint8_t *png; size_t png_len; } Toast;

static pthread_mutex_t g_lock = PTHREAD_MUTEX_INITIALIZER;
static Toast g_queue[QUEUE];
static int g_qhead, g_qlen;
/* the renderer's side, one thread */
static Toast g_cur;
static int g_have_cur, g_drawn_h;
static Uint64 g_start;
static uint32_t *g_px;
static int g_w, g_h;
static unsigned g_serial;
static stbtt_fontinfo g_font;
static int g_font_ok = -1;  /* -1: not tried yet */

void rt_toast_push(const char *head, const char *right, const char *title, const char *text, const void *png, size_t png_len) {
    Toast t;
    memset(&t, 0, sizeof(t));
    snprintf(t.head, sizeof(t.head), "%s", head ? head : "");
    snprintf(t.right, sizeof(t.right), "%s", right ? right : "");
    snprintf(t.title, sizeof(t.title), "%s", title ? title : "");
    snprintf(t.text, sizeof(t.text), "%s", text ? text : "");
    if (png && png_len && (t.png = (uint8_t *)malloc(png_len))) { memcpy(t.png, png, png_len); t.png_len = png_len; }
    pthread_mutex_lock(&g_lock);
    if (g_qlen < QUEUE) { g_queue[(g_qhead + g_qlen) % QUEUE] = t; g_qlen++; t.png = NULL; }
    pthread_mutex_unlock(&g_lock);
    free(t.png);  /* only when the queue was full */
}

/* --- text ---------------------------------------------------------------------------- */
static uint32_t utf8_next(const char **s) {
    const unsigned char *p = (const unsigned char *)*s;
    uint32_t c = *p++;
    int n = c >= 0xF0 ? 3 : c >= 0xE0 ? 2 : c >= 0xC0 ? 1 : 0;
    if (c >= 0x80 && c < 0xC0) { *s = (const char *)p; return '?'; }
    c &= n == 3 ? 0x07u : n == 2 ? 0x0Fu : n == 1 ? 0x1Fu : 0x7Fu;
    for (; n > 0 && (*p & 0xC0) == 0x80; n--) c = c << 6 | (*p++ & 0x3Fu);
    *s = (const char *)p;
    return c;
}

/* the glyph for c, a look-alike when Cinzel lacks it, or -1 to leave it out (emoji, symbols) */
static int glyph_for(uint32_t c) {
    int g = stbtt_FindGlyphIndex(&g_font, (int)c);
    if (g) return g;
    uint32_t alt = c == 0x2018 || c == 0x2019 || c == 0x2032 ? '\'' : c == 0x201C || c == 0x201D ? '"' :
                   c == 0x2013 || c == 0x2014 ? '-' : c == 0xA0 ? ' ' : c < 0x2000 ? '?' : 0;
    return alt ? stbtt_FindGlyphIndex(&g_font, (int)alt) : -1;
}

static float text_width(const char *s, float scale) {
    float w = 0;
    int prev = -1;
    while (*s) {
        int g = glyph_for(utf8_next(&s)), adv, lsb;
        if (g < 0) continue;
        if (prev >= 0) w += scale * (float)stbtt_GetGlyphKernAdvance(&g_font, prev, g);
        stbtt_GetGlyphHMetrics(&g_font, g, &adv, &lsb);
        w += scale * (float)adv;
        prev = g;
    }
    return w;
}

/* s cut to fit maxw, with "..." when it doesn't */
static void fit(const char *s, float maxw, float scale, char *out, size_t n) {
    snprintf(out, n, "%s", s);
    if (text_width(out, scale) <= maxw) return;
    size_t len = strlen(out);
    while (len > 0) {
        do len--; while (len > 0 && ((unsigned char)out[len] & 0xC0) == 0x80);  /* back to a character's start */
        while (len > 0 && out[len - 1] == ' ') len--;
        if (len + 4 > n) continue;
        memcpy(out + len, "...", 4);
        if (text_width(out, scale) <= maxw) return;
    }
    snprintf(out, n, "...");
}

/* the words of s that fit in maxw into out; returns what is left */
static const char *wrap(const char *s, float maxw, float scale, char *out, size_t n) {
    size_t best = 0;
    for (const char *p = s; *p;) {
        const char *e = p;
        while (*e && *e != ' ') e++;
        size_t len = (size_t)(e - s);
        if (len >= n) break;
        memcpy(out, s, len);
        out[len] = 0;
        if (text_width(out, scale) > maxw) break;
        best = len;
        for (p = e; *p == ' '; p++) {}
    }
    if (!best) { fit(s, maxw, scale, out, n); return s + strlen(s); }  /* one word wider than the line */
    memcpy(out, s, best);
    out[best] = 0;
    s += best;
    while (*s == ' ') s++;
    return s;
}

static void fill(int x0, int y0, int w, int h, uint32_t c) {
    for (int y = y0 < 0 ? 0 : y0; y < y0 + h && y < g_h; y++)
        for (int x = x0 < 0 ? 0 : x0; x < x0 + w && x < g_w; x++) g_px[y * g_w + x] = c;
}

static uint32_t rgb(int r, int g, int b) { return 0xFF000000u | (uint32_t)b << 16 | (uint32_t)g << 8 | (uint32_t)r; }  /* RGBA bytes */

/* s from x on the baseline base, px pixels tall (the font's ascent to descent) */
static void draw_text(float x, float base, float px, const char *s, uint32_t color) {
    static unsigned char bm[160 * 160];
    float scale = stbtt_ScaleForPixelHeight(&g_font, px);
    int prev = -1;
    while (*s) {
        int g = glyph_for(utf8_next(&s)), adv, lsb, x0, y0, x1, y1;
        if (g < 0) continue;
        if (prev >= 0) x += scale * (float)stbtt_GetGlyphKernAdvance(&g_font, prev, g);
        stbtt_GetGlyphHMetrics(&g_font, g, &adv, &lsb);
        float fx = x - floorf(x);
        stbtt_GetGlyphBitmapBoxSubpixel(&g_font, g, scale, scale, fx, 0, &x0, &y0, &x1, &y1);
        int gw = x1 - x0, gh = y1 - y0;
        if (gw > 0 && gh > 0 && gw <= 160 && gh <= 160) {
            stbtt_MakeGlyphBitmapSubpixel(&g_font, bm, gw, gh, gw, scale, scale, fx, 0, g);
            int ox = (int)floorf(x) + x0, oy = (int)floorf(base + 0.5f) + y0;
            for (int j = 0; j < gh; j++) {
                int y = oy + j;
                if (y < 0 || y >= g_h) continue;
                for (int i = 0; i < gw; i++) {
                    int xx = ox + i, a = bm[j * gw + i];
                    if (xx < 0 || xx >= g_w || !a) continue;
                    uint32_t d = g_px[y * g_w + xx], o = 0xFF000000u;
                    for (int k = 0; k < 24; k += 8) {
                        int dc = (int)(d >> k & 255), sc = (int)(color >> k & 255);
                        o |= (uint32_t)((dc * (255 - a) + sc * a + 127) / 255) << k;
                    }
                    g_px[y * g_w + xx] = o;
                }
            }
        }
        x += scale * (float)adv;
        prev = g;
    }
}

static void draw_icon(int x, int y, int size) {
    SDL_Surface *png = NULL, *rgba = NULL, *dst = NULL;
    if (g_cur.png) {
        SDL_IOStream *io = SDL_IOFromConstMem(g_cur.png, g_cur.png_len);
        png = io ? SDL_LoadPNG_IO(io, true) : NULL;
        rgba = png ? SDL_ConvertSurface(png, SDL_PIXELFORMAT_RGBA32) : NULL;
        dst = rgba ? SDL_CreateSurfaceFrom(g_w, g_h, SDL_PIXELFORMAT_RGBA32, g_px, g_w * 4) : NULL;
    }
    SDL_Rect r = { x, y, size, size };
    if (dst) {
        SDL_SetSurfaceBlendMode(rgba, SDL_BLENDMODE_BLEND);
        if (!SDL_BlitSurfaceScaled(rgba, NULL, dst, &r, SDL_SCALEMODE_LINEAR)) fill(x, y, size, size, rgb(40, 32, 24));
    } else {
        if (g_cur.png) printf("[toast] icon not shown: %s\n", SDL_GetError());
        fill(x, y, size, size, rgb(40, 32, 24));
    }
    SDL_DestroySurface(dst);
    SDL_DestroySurface(rgba);
    SDL_DestroySurface(png);
}

/* g_cur into g_px, h pixels high: the layout is in hundredths of the height */
static int draw(int h) {
    float u = (float)h / 100.0f;
    int w = (int)lroundf(480.0f * u);
    uint32_t *px = (uint32_t *)realloc(g_px, (size_t)w * (size_t)h * 4);
    if (!px) return 0;
    g_px = px; g_w = w; g_h = h;
    int line = u < 1.5f ? 1 : (int)lroundf(u);
    fill(0, 0, w, h, rgb(176, 140, 72));                               /* bronze frame */
    fill(line, line, w - 2 * line, h - 2 * line, rgb(20, 16, 12));     /* dark panel */
    int ix = (int)lroundf(12 * u), isz = (int)lroundf(76 * u);
    fill(ix - line, ix - line, isz + 2 * line, isz + 2 * line, rgb(120, 96, 52));
    draw_icon(ix, ix, isz);
    float tx = 102 * u, tw = (float)w - tx - 14 * u;
    char buf[400];
    float s_small = stbtt_ScaleForPixelHeight(&g_font, 17 * u), s_title = stbtt_ScaleForPixelHeight(&g_font, 27 * u);
    float rw = g_cur.right[0] ? text_width(g_cur.right, s_small) : 0;
    if (g_cur.right[0]) draw_text((float)w - 14 * u - rw, 30 * u, 17 * u, g_cur.right, rgb(200, 180, 140));
    fit(g_cur.head, tw - rw - (rw > 0 ? 10 * u : 0), s_small, buf, sizeof(buf));
    draw_text(tx, 30 * u, 17 * u, buf, rgb(233, 200, 120));
    fit(g_cur.title, tw, s_title, buf, sizeof(buf));
    draw_text(tx, 58 * u, 27 * u, buf, rgb(246, 240, 228));
    const char *rest = wrap(g_cur.text, tw, s_small, buf, sizeof(buf));
    draw_text(tx, 77 * u, 17 * u, buf, rgb(196, 186, 166));
    if (*rest) {
        fit(rest, tw, s_small, buf, sizeof(buf));
        draw_text(tx, 93 * u, 17 * u, buf, rgb(196, 186, 166));
    }
    return 1;
}

const void *rt_toast_frame(int win_h, int *w, int *h, float *alpha, unsigned *serial) {
    Uint64 now = SDL_GetTicks();
    pthread_mutex_lock(&g_lock);
    for (;;) {
        if (g_have_cur && now - g_start >= FADE_IN_MS + HOLD_MS + FADE_OUT_MS) { free(g_cur.png); g_have_cur = 0; }
        if (g_have_cur || !g_qlen) break;
        g_cur = g_queue[g_qhead];
        g_qhead = (g_qhead + 1) % QUEUE;
        g_qlen--;
        g_have_cur = 1;
        g_start = now;
        g_drawn_h = 0;
    }
    pthread_mutex_unlock(&g_lock);
    if (!g_have_cur) return NULL;
    if (g_font_ok < 0) {
        g_font_ok = stbtt_InitFont(&g_font, MENU_FONT, stbtt_GetFontOffsetForIndex(MENU_FONT, 0));
        if (!g_font_ok) printf("[toast] the built-in font can't be read: no notices on screen\n");
    }
    if (!g_font_ok) return NULL;
    int want = win_h / 10;
    want = want < 56 ? 56 : want > 216 ? 216 : want;
    if (want != g_drawn_h) {
        if (!draw(want)) return NULL;
        g_drawn_h = want;
        g_serial++;
    }
    Uint64 t = now - g_start;
    float a = t < FADE_IN_MS ? (float)t / FADE_IN_MS : t < FADE_IN_MS + HOLD_MS ? 1.0f : 1.0f - (float)(t - FADE_IN_MS - HOLD_MS) / FADE_OUT_MS;
    *alpha = (a < 0 ? 0 : a) * OPACITY;
    *w = g_w;
    *h = g_h;
    *serial = g_serial;
    return g_px;
}

