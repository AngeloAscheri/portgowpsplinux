/* gow_menu: full-screen game picker for Steam's Game Mode, driven by a gamepad. One card per game,
 * with art taken from the player's own disc at install time. It closes its window while a game runs
 * and comes back when the game exits, so Steam sees one running title from the picker to the library.
 *
 *   gow_menu --entry TITLE ART COMMAND [--settings FILE] [--entry ...] [--autostart N]
 *   gow_menu --steam-art DIR APPID ART [ART]     (the pictures of Steam's library, see steam_art)
 *
 * ART is a PNG (a missing one draws a plain card). COMMAND is an executable without arguments; a game
 * whose COMMAND can't be run is shown as unavailable. --settings is the game's own --settings file: Y opens
 * its options, the same as the in-game menu's, and only the ones changed here are written, so the others
 * keep the game's command-line values. --autostart N starts entry N (from 0) once and exits when it ends,
 * without waiting for input. GOW_MENU_TEST_KEYS="y,down,right,b,quit" plays those keys, one per frame,
 * for a test without a gamepad (with SDL_VIDEODRIVER=offscreen, without a window on screen); "right@2" is a
 * press from a second gamepad. */
#include <SDL3/SDL.h>

#include <errno.h>
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/wait.h>
#include <unistd.h>

#include "rt_settings.h"

#define STB_TRUETYPE_IMPLEMENTATION
#define STBTT_STATIC
#include "stb_truetype.h"
#include "gow_menu_font.h"  /* MENU_FONT: Cinzel, generated by CMake */

#define MAX_ENTRIES 4
#define MAX_PADS 8
#define INPUT_GUARD_MS 400  /* a press still held when the window opens must not start or quit anything */
#define TWIN_MS 120         /* the same press from a second gamepad within this is the same press */
#define STICK_ON 20000
#define STICK_OFF 10000

typedef struct {
    const char *title, *art, *cmd, *settings;
    int available;
    SDL_Texture *tex;
} Entry;

typedef struct { const char *label, *key; size_t field; const int *vals; int n; const char *const *names; } OptRow;
#define OPT_ROW(label, key, field, vals, names) \
    { label, key, offsetof(Settings, field), vals, (int)(sizeof(vals) / sizeof(vals[0])), names },
static const OptRow OPT_ROWS[] = { RT_SETTINGS_ROWS(OPT_ROW) };
enum { OPT_N = (int)(sizeof(OPT_ROWS) / sizeof(OPT_ROWS[0])) };
/* What the game runs with when its file doesn't name an option: the values the play scripts pass */
static const Settings OPT_DEFAULT = { .res = 4, .fps = 60, .vsync = 1, .msaa = 1, .aniso = 1, .fullscreen = 1 };

/* Text: MENU_FONT's printable ASCII baked once per pixel size into a texture, drawn with smooth scaling.
 * Without the font, SDL's 8x8 debug font. */
#define FONT_SIZES 6
#define FONT_ATLAS 1024
typedef struct { int px; float cap; SDL_Texture *tex; stbtt_bakedchar ch[96]; } FontSize;
static FontSize g_font[FONT_SIZES];
static stbtt_fontinfo g_font_info;
static int g_font_ok = -1;  /* -1 not tried yet */

/* The options panel of one game: open while g_opt_entry >= 0 */
static int g_opt_entry = -1, g_opt_row, g_opt_idx[OPT_N], g_opt_set[OPT_N], g_opt_changed;

static Entry g_entries[MAX_ENTRIES];
static int g_count, g_sel;
static SDL_Window *g_win;
static SDL_Renderer *g_ren;
static SDL_Gamepad *g_pads[MAX_PADS];
static int g_stick_latched;

static int ui_open(void) {
    SDL_SetHint(SDL_HINT_APP_NAME, "God of War PSP native port");
    if (!SDL_Init(SDL_INIT_VIDEO | SDL_INIT_GAMEPAD)) { fprintf(stderr, "[menu] SDL_Init: %s\n", SDL_GetError()); return 0; }
    if (!SDL_CreateWindowAndRenderer("God of War PSP", 1280, 720, SDL_WINDOW_FULLSCREEN, &g_win, &g_ren)) {
        fprintf(stderr, "[menu] window: %s\n", SDL_GetError());
        return 0;
    }
    SDL_SetRenderVSync(g_ren, 1);
    SDL_HideCursor();
    for (int i = 0; i < g_count; i++) {
        SDL_Surface *s = g_entries[i].art && *g_entries[i].art ? SDL_LoadPNG(g_entries[i].art) : NULL;
        if (!s) continue;
        g_entries[i].tex = SDL_CreateTextureFromSurface(g_ren, s);
        SDL_DestroySurface(s);
    }
    g_stick_latched = 0;
    int pads = 0;
    SDL_free(SDL_GetGamepads(&pads));
    printf("[menu] window open; %d gamepad%s\n", pads, pads == 1 ? "" : "s");
    return 1;
}

static void font_close(void) {
    for (int i = 0; i < FONT_SIZES; i++) {
        if (g_font[i].tex) SDL_DestroyTexture(g_font[i].tex);
        g_font[i].tex = NULL;
        g_font[i].px = 0;
    }
}

static void ui_close(void) {
    font_close();
    for (int i = 0; i < g_count; i++) {
        if (g_entries[i].tex) SDL_DestroyTexture(g_entries[i].tex);
        g_entries[i].tex = NULL;
    }
    for (int i = 0; i < MAX_PADS; i++) {
        if (g_pads[i]) SDL_CloseGamepad(g_pads[i]);
        g_pads[i] = NULL;
    }
    if (g_ren) SDL_DestroyRenderer(g_ren);
    if (g_win) SDL_DestroyWindow(g_win);
    g_ren = NULL;
    g_win = NULL;
    SDL_Quit();  /* the game opens the gamepads and the display itself */
}

static void open_pad(SDL_JoystickID id) {
    for (int i = 0; i < MAX_PADS; i++) {
        if (g_pads[i]) continue;
        g_pads[i] = SDL_OpenGamepad(id);
        if (g_pads[i]) printf("[menu] gamepad connected: %s\n", SDL_GetGamepadName(g_pads[i]));
        return;
    }
}

static void close_pad(SDL_JoystickID id) {
    for (int i = 0; i < MAX_PADS; i++) {
        if (g_pads[i] && SDL_GetGamepadID(g_pads[i]) == id) { SDL_CloseGamepad(g_pads[i]); g_pads[i] = NULL; }
    }
}

/* Runs a game with no window of ours open, and waits for it. */
static int run_game(const Entry *e) {
    fflush(NULL);
    ui_close();
    pid_t pid = fork();
    if (pid < 0) { fprintf(stderr, "[menu] fork: %s\n", strerror(errno)); return ui_open() ? 0 : -1; }
    if (pid == 0) {
        execl(e->cmd, e->cmd, (char *)NULL);
        fprintf(stderr, "[menu] %s: %s\n", e->cmd, strerror(errno));
        _exit(127);
    }
    int st = 0;
    while (waitpid(pid, &st, 0) < 0 && errno == EINTR) {}
    printf("[menu] %s ended (%s %d)\n", e->title, WIFSIGNALED(st) ? "signal" : "exit",
           WIFSIGNALED(st) ? WTERMSIG(st) : WEXITSTATUS(st));
    return ui_open() ? 1 : -1;
}

/* The baked font for text drawn at debug-font scale `scale` (8 x scale pixels a line), or NULL */
static FontSize *font_for(float scale) {
    if (g_font_ok < 0) {
        g_font_ok = stbtt_InitFont(&g_font_info, MENU_FONT, stbtt_GetFontOffsetForIndex(MENU_FONT, 0));
        if (!g_font_ok) fprintf(stderr, "[menu] the built-in font can't be read: using SDL's debug font\n");
    }
    if (!g_font_ok) return NULL;
    int x0, y0, x1, cap_units;  /* sized so its capitals are as tall as the debug font's, 7 of its 8 pixels */
    stbtt_GetCodepointBox(&g_font_info, 'H', &x0, &y0, &x1, &cap_units);
    float per_px = (float)cap_units * stbtt_ScaleForPixelHeight(&g_font_info, 1.0f);
    int px = (int)(7.0f * scale / (per_px > 0.1f ? per_px : 0.7f) + 0.5f);
    for (int i = 0; i < FONT_SIZES; i++) if (g_font[i].px == px && g_font[i].tex) return &g_font[i];
    FontSize *f = NULL;
    for (int i = 0; i < FONT_SIZES && !f; i++) if (!g_font[i].tex) f = &g_font[i];
    if (!f) { font_close(); f = &g_font[0]; }
    unsigned char *bits = malloc(FONT_ATLAS * FONT_ATLAS);
    SDL_Surface *s = bits ? SDL_CreateSurface(FONT_ATLAS, FONT_ATLAS, SDL_PIXELFORMAT_RGBA32) : NULL;
    if (s && stbtt_BakeFontBitmap(MENU_FONT, stbtt_GetFontOffsetForIndex(MENU_FONT, 0), (float)px, bits, FONT_ATLAS,
                                  FONT_ATLAS, 32, 96, f->ch) != 0) {
        for (int y = 0; y < FONT_ATLAS; y++) {
            Uint32 *row = (Uint32 *)((Uint8 *)s->pixels + y * s->pitch);
            for (int x = 0; x < FONT_ATLAS; x++) row[x] = SDL_MapSurfaceRGBA(s, 255, 255, 255, bits[y * FONT_ATLAS + x]);
        }
        f->tex = SDL_CreateTextureFromSurface(g_ren, s);
    }
    if (f->tex) {
        f->cap = (float)cap_units * stbtt_ScaleForPixelHeight(&g_font_info, (float)px);
        f->px = px;
        SDL_SetTextureBlendMode(f->tex, SDL_BLENDMODE_BLEND);
        SDL_SetTextureScaleMode(f->tex, SDL_SCALEMODE_LINEAR);
    }
    else fprintf(stderr, "[menu] text at %d pixels: no texture, using SDL's debug font\n", px);
    SDL_DestroySurface(s);
    free(bits);
    return f->tex ? f : NULL;
}

static float text_width(float scale, const char *s) {
    FontSize *f = font_for(scale);
    if (!f) return (float)strlen(s) * 8.0f * scale;
    float w = 0;
    for (; *s; s++) if (*s >= 32 && *s < 127) w += f->ch[*s - 32].xadvance;
    return w;
}

/* Text in the current draw color, its top at y like SDL_RenderDebugText's */
static void text_at(float x, float y, float scale, const char *s) {
    FontSize *f = font_for(scale);
    if (!f) {
        SDL_SetRenderScale(g_ren, scale, scale);
        SDL_RenderDebugText(g_ren, x / scale, y / scale, s);
        SDL_SetRenderScale(g_ren, 1.0f, 1.0f);
        return;
    }
    Uint8 r, g, b, a;
    SDL_GetRenderDrawColor(g_ren, &r, &g, &b, &a);
    SDL_SetTextureColorMod(f->tex, r, g, b);
    SDL_SetTextureAlphaMod(f->tex, a);
    float bx = x, by = y + f->cap;  /* the baseline: capitals from y down, like the debug font's */
    for (; *s; s++) {
        if (*s < 32 || *s >= 127) continue;
        stbtt_aligned_quad q;
        stbtt_GetBakedQuad(f->ch, FONT_ATLAS, FONT_ATLAS, *s - 32, &bx, &by, &q, 1);
        SDL_FRect src = { q.s0 * FONT_ATLAS, q.t0 * FONT_ATLAS, (q.s1 - q.s0) * FONT_ATLAS, (q.t1 - q.t0) * FONT_ATLAS };
        SDL_FRect dst = { q.x0, q.y0, q.x1 - q.x0, q.y1 - q.y0 };
        SDL_RenderTexture(g_ren, f->tex, &src, &dst);
    }
}

static void text_centered(float cx, float y, float scale, const char *s) {
    text_at(cx - text_width(scale, s) / 2.0f, y, scale, s);
}

/* The options panel over the cards. Every change takes effect the next time the game opens. */
static void draw_options(int w, int h, float text) {
    float line = text * 12.0f, pw = text * 8.0f * 44.0f, ph = line * (float)(OPT_N + 5);
    if (pw > (float)w * 0.9f) pw = (float)w * 0.9f;
    SDL_FRect r = { ((float)w - pw) / 2.0f, ((float)h - ph) / 2.0f, pw, ph };
    SDL_SetRenderDrawColor(g_ren, 233, 214, 164, 255);
    SDL_FRect border = { r.x - text, r.y - text, r.w + 2 * text, r.h + 2 * text };
    SDL_RenderFillRect(g_ren, &border);
    SDL_SetRenderDrawColor(g_ren, 18, 14, 12, 255);
    SDL_RenderFillRect(g_ren, &r);
    SDL_SetRenderDrawColor(g_ren, 233, 214, 164, 255);
    text_centered((float)w / 2.0f, r.y + line, text, g_entries[g_opt_entry].title);
    float lx = r.x + text * 16.0f, vx = r.x + pw * 0.62f;
    for (int i = 0; i < OPT_N; i++) {
        const OptRow *o = &OPT_ROWS[i];
        float y = r.y + line * (float)(i + 3);
        char label[64], value[64];
        snprintf(label, sizeof(label), "%.*s", (int)strcspn(o->label, "("), o->label);  /* "MSAA (al reiniciar)" */
        snprintf(value, sizeof(value), "< %s >", o->names[g_opt_idx[i]]);
        Uint8 c = i == g_opt_row ? 255 : 150;
        SDL_SetRenderDrawColor(g_ren, c, c, c, 255);
        if (i == g_opt_row) SDL_SetRenderDrawColor(g_ren, 233, 214, 164, 255);
        text_at(lx, y, text, label);
        text_at(vx, y, text, value);
    }
    SDL_SetRenderDrawColor(g_ren, 180, 170, 150, 255);
    int fps = 60;
    for (int i = 0; i < OPT_N; i++) if (!strcmp(OPT_ROWS[i].key, "fps")) fps = OPT_ROWS[i].vals[g_opt_idx[i]];
    text_centered((float)w / 2.0f, r.y + line * (float)(OPT_N + 3), text * 0.75f,
                  fps > 60 ? "Arriba de 60 FPS los videos se traban" : "Se aplica al abrir el juego");
    text_centered((float)w / 2.0f, r.y + line * (float)(OPT_N + 4), text * 0.75f,
                  "Arriba/Abajo: elegir   Izq/Der: cambiar");
}

static void draw(void) {
    int w = 1280, h = 720;
    SDL_GetCurrentRenderOutputSize(g_ren, &w, &h);
    float text = (float)(h / 240 > 2 ? h / 240 : 2), gap = (float)w * 0.04f;
    float card_w = ((float)w - gap * (float)(g_count + 1)) / (float)g_count;
    float card_h = card_w * 272.0f / 480.0f;  /* the disc's art is the PSP's screen shape */
    if (card_h > (float)h * 0.6f) { card_h = (float)h * 0.6f; card_w = card_h * 480.0f / 272.0f; }
    float total = card_w * (float)g_count + gap * (float)(g_count - 1);
    float x = ((float)w - total) / 2.0f, y = ((float)h - card_h) / 2.0f;

    SDL_SetRenderDrawColor(g_ren, 10, 8, 8, 255);
    SDL_RenderClear(g_ren);
    SDL_SetRenderDrawColor(g_ren, 233, 214, 164, 255);
    text_centered((float)w / 2.0f, y / 2.0f - text * 4.0f, text * 1.5f, "GOD OF WAR PSP");

    for (int i = 0; i < g_count; i++) {
        const Entry *e = &g_entries[i];
        int sel = i == g_sel;
        SDL_FRect r = { x + (card_w + gap) * (float)i, y, card_w, card_h };
        if (sel) {
            float b = text * 2.0f;
            SDL_FRect border = { r.x - b, r.y - b, r.w + 2 * b, r.h + 2 * b };
            SDL_SetRenderDrawColor(g_ren, 233, 214, 164, 255);
            SDL_RenderFillRect(g_ren, &border);
        }
        if (e->tex) {
            Uint8 c = !e->available ? 60 : sel ? 255 : 130;
            SDL_SetTextureColorMod(e->tex, c, c, c);
            SDL_RenderTexture(g_ren, e->tex, NULL, &r);
        } else {
            SDL_SetRenderDrawColor(g_ren, 40, 32, 28, 255);
            SDL_RenderFillRect(g_ren, &r);
        }
        float cx = r.x + r.w / 2.0f, ty = r.y + r.h + text * 8.0f;
        Uint8 c = sel ? 255 : 150;
        SDL_SetRenderDrawColor(g_ren, c, c, c, 255);
        text_centered(cx, ty, text, e->title);
        if (!e->available) text_centered(cx, ty + text * 12.0f, text * 0.75f, "No disponible");
    }
    SDL_SetRenderDrawColor(g_ren, 180, 170, 150, 255);
    if (g_opt_entry >= 0) {
        draw_options(w, h, text);
        SDL_SetRenderDrawColor(g_ren, 180, 170, 150, 255);
        text_centered((float)w / 2.0f, (float)h - text * 16.0f, text, "Y: OK");
    } else {
        text_centered((float)w / 2.0f, (float)h - text * 16.0f, text,
                      g_entries[g_sel].settings ? "A: Jugar     Y: Opciones     B: Salir" : "A: Jugar     B: Salir");
    }
    SDL_RenderPresent(g_ren);
}

static void move_selection(int d) {
    g_sel = (g_sel + d + g_count) % g_count;
}

static int opt_index(int row, int value) {
    for (int k = 0; k < OPT_ROWS[row].n; k++) if (OPT_ROWS[row].vals[k] == value) return k;
    return -1;
}

/* key=value -> row and value index; -1 for a line that isn't one of the options with one of its values */
static int opt_parse(const char *line, int *idx) {
    char key[64];
    int value;
    if (sscanf(line, "%63[^=]=%d", key, &value) != 2) return -1;
    for (int r = 0; r < OPT_N; r++)
        if (!strcmp(key, OPT_ROWS[r].key)) return (*idx = opt_index(r, value)) >= 0 ? r : -1;
    return -1;
}

static void opt_open(int entry) {
    g_opt_entry = entry;
    g_opt_row = 0;
    g_opt_changed = 0;
    for (int r = 0; r < OPT_N; r++) {
        int k = opt_index(r, *(const int *)((const char *)&OPT_DEFAULT + OPT_ROWS[r].field));
        g_opt_idx[r] = k < 0 ? 0 : k;
        g_opt_set[r] = 0;
    }
    FILE *f = fopen(g_entries[entry].settings, "r");
    if (!f) return;
    char line[128];
    int k, r;
    while (fgets(line, sizeof(line), f))
        if ((r = opt_parse(line, &k)) >= 0) { g_opt_idx[r] = k; g_opt_set[r] = 1; }
    fclose(f);
}

/* Rewrites the file with the options the file had or the panel changed; other lines stay as they were. */
static void opt_close(void) {
    const char *path = g_entries[g_opt_entry].settings;
    g_opt_entry = -1;
    if (!g_opt_changed) return;
    char tmp[1024], line[128];
    snprintf(tmp, sizeof(tmp), "%s.tmp", path);
    FILE *out = fopen(tmp, "w");
    if (!out) { fprintf(stderr, "[menu] %s: %s\n", tmp, strerror(errno)); return; }
    int done[OPT_N] = { 0 }, k, r;
    FILE *in = fopen(path, "r");
    while (in && fgets(line, sizeof(line), in)) {
        if ((r = opt_parse(line, &k)) < 0) { fputs(line, out); continue; }
        if (!done[r]) fprintf(out, "%s=%d\n", OPT_ROWS[r].key, OPT_ROWS[r].vals[g_opt_idx[r]]);
        done[r] = 1;
    }
    if (in) fclose(in);
    for (r = 0; r < OPT_N; r++)
        if (g_opt_set[r] && !done[r]) fprintf(out, "%s=%d\n", OPT_ROWS[r].key, OPT_ROWS[r].vals[g_opt_idx[r]]);
    if (fclose(out) != 0 || rename(tmp, path) != 0) { fprintf(stderr, "[menu] %s: %s\n", path, strerror(errno)); return; }
    printf("[menu] options written to %s\n", path);
}

static void opt_move(int d) {
    g_opt_row = (g_opt_row + d + OPT_N) % OPT_N;
}

static void opt_change(int d) {
    const OptRow *o = &OPT_ROWS[g_opt_row];
    g_opt_idx[g_opt_row] = (g_opt_idx[g_opt_row] + d + o->n) % o->n;
    g_opt_set[g_opt_row] = 1;
    g_opt_changed = 1;
}

enum { IN_LEFT, IN_RIGHT, IN_UP, IN_DOWN, IN_PLAY, IN_BACK, IN_OPTIONS };

/* With Steam Input on a desktop, SDL sees the gamepad twice (Steam's virtual one and the real one): a press
 * arrives from both, which opened and closed the options at once, moved two values and quit after a B. The same
 * press from another gamepad within TWIN_MS is dropped. */
static int twin(int in, SDL_JoystickID dev) {
    static int last_in = -1;
    static SDL_JoystickID last_dev;
    static Uint64 last_ms;
    Uint64 now = SDL_GetTicks();
    int same = in == last_in && dev != last_dev && now - last_ms < TWIN_MS;
    if (!same) { last_in = in; last_dev = dev; last_ms = now; }
    return same;
}

/* One button or key press: returns 1 to start the chosen game, -1 to quit. */
static int press(int in) {
    if (g_opt_entry >= 0) {
        if (in == IN_UP || in == IN_DOWN) opt_move(in == IN_UP ? -1 : 1);
        else if (in == IN_LEFT || in == IN_RIGHT) opt_change(in == IN_LEFT ? -1 : 1);
        else if (in == IN_BACK || in == IN_OPTIONS) opt_close();
        return 0;
    }
    if (in == IN_LEFT || in == IN_RIGHT) move_selection(in == IN_LEFT ? -1 : 1);
    else if (in == IN_PLAY) return 1;
    else if (in == IN_BACK) return -1;
    else if (in == IN_OPTIONS && g_entries[g_sel].settings) opt_open(g_sel);
    return 0;
}

/* GOW_MENU_TEST_KEYS: the next key of the list, or -2 once it is over ("quit" ends the picker); "right@2" comes
 * from gamepad 2 (default 1), to test twin presses */
static int test_key(SDL_JoystickID *dev) {
    static const char *next;
    static const struct { const char *name; int in; } names[] = {
        { "left", IN_LEFT }, { "right", IN_RIGHT }, { "up", IN_UP }, { "down", IN_DOWN },
        { "a", IN_PLAY }, { "b", IN_BACK }, { "y", IN_OPTIONS }, { "quit", -1 },
    };
    if (!next) next = getenv("GOW_MENU_TEST_KEYS");
    if (!next || !*next) return -2;
    size_t len = strcspn(next, ","), name_len = strcspn(next, ",@");
    int in = -3;
    *dev = name_len < len ? (SDL_JoystickID)atoi(next + name_len + 1) : 1;
    for (size_t i = 0; i < sizeof(names) / sizeof(names[0]); i++)
        if (strlen(names[i].name) == name_len && !strncmp(next, names[i].name, name_len)) in = names[i].in;
    next += len + (next[len] == ',');
    return in;
}

/* --steam-art DIR APPID ART...: the pictures Steam's library shows for the shortcut (launcher.pyw --add-to-steam),
 * made from the games' card art (PIC1.PNG off the player's discs): DIR/<APPID>p.png (portrait capsule, 600x900),
 * <APPID>.png (wide capsule, 920x430), <APPID>_hero.png (1920x620) and <APPID>_logo.png (the title, transparent).
 * With two pictures each takes half; drawn with a software renderer, no window. */
static void cover(SDL_Texture *t, SDL_FRect d) {  /* t fills d, cropped around its centre */
    float tw, th;
    SDL_GetTextureSize(t, &tw, &th);
    float s = d.w / tw > d.h / th ? d.w / tw : d.h / th;
    SDL_FRect src = { (tw - d.w / s) / 2.0f, (th - d.h / s) / 2.0f, d.w / s, d.h / s };
    SDL_RenderTexture(g_ren, t, &src, &d);
}

static int steam_art(const char *dir, const char *appid, int n, char **arts) {
    static const struct { const char *suffix; int w, h, kind; } pics[] = {  /* kind: 0 art and title, 1 art, 2 title */
        { "p.png", 600, 900, 0 }, { ".png", 920, 430, 0 }, { "_hero.png", 1920, 620, 1 }, { "_logo.png", 1280, 360, 2 },
    };
    SDL_Surface *art[2] = { NULL, NULL };
    for (int i = 0; i < n && i < 2; i++)
        if (!(art[i] = SDL_LoadPNG(arts[i]))) { fprintf(stderr, "[menu] %s: %s\n", arts[i], SDL_GetError()); return 1; }
    n = n < 2 ? n : 2;
    for (size_t p = 0; p < sizeof(pics) / sizeof(pics[0]); p++) {
        int w = pics[p].w, h = pics[p].h, tall = h > w;
        SDL_Surface *s = SDL_CreateSurface(w, h, SDL_PIXELFORMAT_RGBA32);
        g_ren = s ? SDL_CreateSoftwareRenderer(s) : NULL;
        if (!g_ren) { fprintf(stderr, "[menu] steam art: %s\n", SDL_GetError()); return 1; }
        SDL_SetRenderDrawBlendMode(g_ren, SDL_BLENDMODE_BLEND);
        SDL_SetRenderDrawColor(g_ren, 10, 8, 8, pics[p].kind == 2 ? 0 : 255);
        SDL_RenderClear(g_ren);
        if (pics[p].kind != 2)
            for (int i = 0; i < n; i++) {
                SDL_Texture *t = SDL_CreateTextureFromSurface(g_ren, art[i]);
                SDL_FRect d = tall ? (SDL_FRect){ 0, (float)h * i / n, (float)w, (float)h / n } : (SDL_FRect){ (float)w * i / n, 0, (float)w / n, (float)h };
                if (t) cover(t, d);
                SDL_DestroyTexture(t);
            }
        if (pics[p].kind != 1) {
            float scale = (float)w / (pics[p].kind == 2 ? 120.0f : 110.0f), y = (float)h / 2.0f - 4.0f * scale;
            if (pics[p].kind == 0) {  /* a dark band for the title */
                SDL_SetRenderDrawColor(g_ren, 0, 0, 0, 170);
                SDL_FRect band = { 0, y - 5.0f * scale, (float)w, 18.0f * scale };
                SDL_RenderFillRect(g_ren, &band);
            }
            SDL_SetRenderDrawColor(g_ren, 0, 0, 0, 255);
            text_centered((float)w / 2.0f + scale * 0.4f, y + scale * 0.4f, scale, "GOD OF WAR");
            SDL_SetRenderDrawColor(g_ren, 233, 214, 164, 255);
            text_centered((float)w / 2.0f, y, scale, "GOD OF WAR");
            text_centered((float)w / 2.0f, y + 9.0f * scale, scale * 0.45f, "CHAINS OF OLYMPUS  -  GHOST OF SPARTA");
        }
        SDL_RenderPresent(g_ren);
        char path[1024];
        snprintf(path, sizeof(path), "%s/%s%s", dir, appid, pics[p].suffix);
        font_close();
        SDL_DestroyRenderer(g_ren);
        g_ren = NULL;
        int ok = SDL_SavePNG(s, path);
        SDL_DestroySurface(s);
        if (!ok) { fprintf(stderr, "[menu] %s: %s\n", path, SDL_GetError()); return 1; }
        printf("[menu] steam art %s\n", path);
    }
    for (int i = 0; i < 2; i++) SDL_DestroySurface(art[i]);
    return 0;
}

int main(int argc, char **argv) {
    int autostart = -1;
    setvbuf(stdout, NULL, _IOLBF, 0);  /* the log is a file (launcher.pyw --menu): keep each line even when Steam ends us */
    if (argc >= 5 && !strcmp(argv[1], "--steam-art")) return steam_art(argv[2], argv[3], argc - 4, argv + 4);
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--entry") && i + 3 < argc && g_count < MAX_ENTRIES) {
            Entry *e = &g_entries[g_count++];
            e->title = argv[++i];
            e->art = argv[++i];
            e->cmd = argv[++i];
            e->available = access(e->cmd, X_OK) == 0;
        } else if (!strcmp(argv[i], "--settings") && i + 1 < argc && g_count > 0) {
            g_entries[g_count - 1].settings = argv[++i];
        } else if (!strcmp(argv[i], "--autostart") && i + 1 < argc) {
            autostart = atoi(argv[++i]);
        } else {
            fprintf(stderr, "usage: %s --entry TITLE ART COMMAND [--settings FILE] [--entry ...] [--autostart N]\n", argv[0]);
            return 2;
        }
    }
    if (!g_count) { fprintf(stderr, "[menu] no games given\n"); return 2; }
    for (int i = g_count - 1; i >= 0; i--) if (g_entries[i].available) g_sel = i;  /* start on the first playable one */

    if (!ui_open()) return 1;
    if (autostart >= 0) {
        int ok = autostart < g_count && g_entries[autostart].available && run_game(&g_entries[autostart]) > 0;
        ui_close();
        return ok ? 0 : 1;
    }

    Uint64 guard = SDL_GetTicks() + INPUT_GUARD_MS;
    for (int quit = 0; !quit;) {
        int start = 0, in = -1;
        SDL_Event ev;
        while (SDL_PollEvent(&ev)) {
            int live = SDL_GetTicks() >= guard;
            in = -1;
            switch (ev.type) {
            case SDL_EVENT_QUIT: quit = 1; break;
            case SDL_EVENT_GAMEPAD_ADDED: open_pad(ev.gdevice.which); break;
            case SDL_EVENT_GAMEPAD_REMOVED: close_pad(ev.gdevice.which); break;
            case SDL_EVENT_GAMEPAD_BUTTON_DOWN:
                if (!live) break;
                if (ev.gbutton.button == SDL_GAMEPAD_BUTTON_DPAD_LEFT) in = IN_LEFT;
                else if (ev.gbutton.button == SDL_GAMEPAD_BUTTON_DPAD_RIGHT) in = IN_RIGHT;
                else if (ev.gbutton.button == SDL_GAMEPAD_BUTTON_DPAD_UP) in = IN_UP;
                else if (ev.gbutton.button == SDL_GAMEPAD_BUTTON_DPAD_DOWN) in = IN_DOWN;
                else if (ev.gbutton.button == SDL_GAMEPAD_BUTTON_SOUTH) in = IN_PLAY;
                else if (ev.gbutton.button == SDL_GAMEPAD_BUTTON_EAST) in = IN_BACK;
                else if (ev.gbutton.button == SDL_GAMEPAD_BUTTON_NORTH) in = IN_OPTIONS;
                break;
            case SDL_EVENT_GAMEPAD_AXIS_MOTION:
                if (ev.gaxis.axis != SDL_GAMEPAD_AXIS_LEFTX && ev.gaxis.axis != SDL_GAMEPAD_AXIS_LEFTY) break;
                if (abs(ev.gaxis.value) < STICK_OFF) g_stick_latched &= ~(1 << ev.gaxis.axis);
                else if (live && !(g_stick_latched & (1 << ev.gaxis.axis)) && abs(ev.gaxis.value) > STICK_ON) {
                    g_stick_latched |= 1 << ev.gaxis.axis;
                    if (ev.gaxis.axis == SDL_GAMEPAD_AXIS_LEFTX) in = ev.gaxis.value < 0 ? IN_LEFT : IN_RIGHT;
                    else in = ev.gaxis.value < 0 ? IN_UP : IN_DOWN;
                }
                break;
            case SDL_EVENT_KEY_DOWN:
                if (!live || ev.key.repeat) break;
                if (ev.key.key == SDLK_LEFT) in = IN_LEFT;
                else if (ev.key.key == SDLK_RIGHT) in = IN_RIGHT;
                else if (ev.key.key == SDLK_UP) in = IN_UP;
                else if (ev.key.key == SDLK_DOWN) in = IN_DOWN;
                else if (ev.key.key == SDLK_RETURN) in = IN_PLAY;
                else if (ev.key.key == SDLK_ESCAPE || ev.key.key == SDLK_BACKSPACE) in = IN_BACK;
                else if (ev.key.key == SDLK_Y || ev.key.key == SDLK_TAB) in = IN_OPTIONS;
                break;
            default: break;
            }
            if (in >= 0 && (ev.type == SDL_EVENT_GAMEPAD_BUTTON_DOWN || ev.type == SDL_EVENT_GAMEPAD_AXIS_MOTION) &&
                twin(in, ev.type == SDL_EVENT_GAMEPAD_BUTTON_DOWN ? ev.gbutton.which : ev.gaxis.which))
                in = -1;
            if (in >= 0) {
                int r = press(in);
                if (r > 0) start = 1;
                else if (r < 0) quit = 1;
            }
        }
        SDL_JoystickID test_dev;
        if (SDL_GetTicks() >= guard && (in = test_key(&test_dev)) != -2) {
            int r = in == -1 ? -1 : in >= 0 && !twin(in, test_dev) ? press(in) : 0;
            if (r > 0) start = 1;
            else if (r < 0) quit = 1;
        }
        if (start && !quit && g_entries[g_sel].available) {
            if (run_game(&g_entries[g_sel]) < 0) return 1;
            guard = SDL_GetTicks() + INPUT_GUARD_MS;
            continue;
        }
        draw();
    }
    ui_close();
    return 0;
}
